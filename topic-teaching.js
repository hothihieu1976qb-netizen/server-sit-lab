function topicPrelude(lesson){
  const [concept,input,action,reading]=TOPIC_EXAMPLES[lesson.id];
  return '<section class="topic-prelude starter-guide"><h3>先弄懂这节课要解决什么</h3><p>'+esc(concept)+'</p>'+renderTerms([lesson.title,lesson.goal,concept,input].join(' '))+'<h4>先看一个小例子</h4><pre>'+esc(input)+'</pre><h4>可以怎样做</h4><p>'+esc(action)+'</p><h4>从这个例子能学到什么</h4><p>'+esc(reading)+'</p><p class="muted">这是教学小例子。下面的任务需要你在自己的本轮环境里实际操作或分析。</p></section>';
}

function renderAcademyCommandGuide(lesson){
  if(!lesson.commands?.length||!$('academy-command-guide'))return;
  const selected=S.ui.academyGuide?.lessonId===lesson.id?Math.min(S.ui.academyGuide.index,lesson.commands.length-1):0;
  renderStarterGuide('academy-command-guide',{lesson,commands:lesson.commands,index:selected,run:projectEngine()});
}
